def page(title, body):
    return (f"<!doctype html><html lang='en'><head><meta charset='utf-8'>"
            f"<meta name='viewport' content='width=device-width,initial-scale=1'><title>{esc(title)}</title>"
            f"<style>{CSS}</style></head><body><main>{body}<footer>Built by Avinash Rayudu. All brands, files and "
            f"numbers are synthetic. Not affiliated with any company named in the exports.</footer></main></body></html>")


def pill(status):
    s = str(status)
    cls = "ok" if s in ("accepted", "pass") else ("bad" if s in ("blocked", "fail") else
                                                  ("na" if s == "n/a" else "warn"))
    return f"<span class='pill {cls}'>{esc(s)}</span>"


def table(headers, rows, num_cols=()):
    h = "".join(f"<th class='{'num' if i in num_cols else ''}'>{esc(x)}</th>" for i, x in enumerate(headers))
    body = []
    for r in rows:
        cells = []
        for i, x in enumerate(r):
            cls = "num" if i in num_cols else ""
            if isinstance(x, tuple) and x[0] == "raw":
                cells.append(f"<td class='{cls}'>{x[1]}</td>")
            elif isinstance(x, tuple) and x[0] == "wrap":
                cells.append(f"<td class='wrap'>{esc(x[1])}</td>")
            else:
                cells.append(f"<td class='{cls}'>{esc(x)}</td>")
        body.append("<tr>" + "".join(cells) + "</tr>")
    return f"<div class='tablewrap'><table><thead><tr>{h}</tr></thead><tbody>{''.join(body)}</tbody></table></div>"


