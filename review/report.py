"""
Writes the human-readable outputs of an evaluation run:
  evals/results/results.md     markdown summary (renders on GitHub)
  reports/index.html           overview page, self-contained, works on GitHub Pages
  reports/<brand>.html         one page per brand: checks, files, review queue, money

Built by Avinash Rayudu.
"""
from __future__ import annotations

import html
import json
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
REP = ROOT / "reports"
RES = ROOT / "evals" / "results"
UPLOADS = ("upload_1", "upload_2")
SPLIT_NAME = {"train": "Training brands (in-sample)", "dev": "Development brands (never trained on)",
              "holdout": "Holdout brands"}


def pct(x, d=1):
    return "n/a" if x is None else f"{100 * x:.{d}f}%"


def money(x):
    return "n/a" if x is None else f"{x:,.0f}"


def esc(x):
    return html.escape(str(x))


def wrongly_accepted(src, split, up):
    """Brands accepted after review whose customer receipts are off by more than 1% from the truth."""
    n = 0
    for b in src["brands"]:
        if b["split"] != split:
            continue
        u = b["uploads"][up]
        e = u["receipts"]["pipeline_error_pct"]
        if u["final"]["status"] == "accepted" and e is not None and abs(e) > 1.0:
            n += 1
    return n


def load_v1():
    p = RES / "holdout_v1_frozen" / "results.json"
    return json.loads(p.read_text()) if p.exists() else None


# --------------------------------------------------------------------------- markdown
def write_md(out, v1):
    L = ["# Evaluation results", "",
         "Synthetic data. Generated by `make demo` (or `python evals/run_evals.py`). Built by Avinash Rayudu.", ""]
    fz = out.get("freeze", {})
    if fz.get("matches") is False:
        L += [f"> Code changed after the pre-holdout freeze ({', '.join(fz['changed_after_freeze'])}). "
              "Holdout numbers in the tables below are **not blind**. The blind holdout run is kept unchanged in "
              "`evals/results/holdout_v1_frozen/`.", ""]
    m = out["model"]
    L += ["## Model", "",
          f"- Trained on {len(m['trained_on'])} brands, {m['n_training_lines']} labeled bank and card lines, "
          f"{m['n_training_accounts']} accounts.",
          f"- Leave-one-brand-out accuracy without abstaining: lines {pct(m['cv_line']['accuracy_no_abstain'])}, "
          f"accounts {pct(m['cv_coa']['accuracy_no_abstain'])}.",
          f"- Abstain threshold chosen for {pct(m['target_precision'], 0)} precision on held-out brands: lines "
          f"{m['line_threshold']}, accounts {m['coa_threshold']}.", ""]
    L += ["## First pass, before any review", "",
          "| split | upload | lines | auto-labeled | precision | wrong | to review | files auto / total | "
          "wrong files accepted | review items per brand | accepted after review | duplicates caught |",
          "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for split in ("dev", "holdout", "train"):
        a = out["aggregate"].get(split)
        if not a:
            continue
        for up in UPLOADS:
            x = a[up]
            L.append(f"| {split} | {up} | {x['lines']} | {pct(x['coverage'])} | {pct(x['precision'])} | "
                     f"{x['label_errors']} | {x['lines_to_review']} | {x['files_auto']} / {x['files']} | "
                     f"{x['files_wrong_but_accepted']} | {x['review_items_per_brand']} | "
                     f"{x['brands_accepted_after_review']} / {a['brands']} | "
                     f"{x['duplicates']['caught']} / {x['duplicates']['truth']} |")
    L += ["", "Training brands are in-sample and are shown only for completeness.", ""]
    if v1 and v1["aggregate"].get("holdout"):
        L += ["## Holdout: blind run vs. after fixes", "",
              "| run | upload | auto-labeled | precision | wrong files accepted | accepted after review | "
              "accepted but wrong (receipts off by >1%) | receipts error (max) |", "|---|---|---|---|---|---|---|---|"]
        for tag, src in (("v1 blind (frozen code)", v1), ("v2 after fixes (not blind)", out)):
            a = src["aggregate"].get("holdout")
            if not a:
                continue
            for up in UPLOADS:
                x = a[up]
                L.append(f"| {tag} | {up} | {pct(x['coverage'])} | {pct(x['precision'])} | "
                         f"{x['files_wrong_but_accepted']} | {x['brands_accepted_after_review']} / {a['brands']} | "
                         f"{wrongly_accepted(src, 'holdout', up)} | {x['receipts_abs_error_pct_max']}% |")
        L.append("")
    L += ["## Per brand", "",
          "| brand | split | upload | first pass | review items | auto-labeled | precision | final | "
          "receipts error | naive overstatement |", "|---|---|---|---|---|---|---|---|---|---|"]
    for b in sorted(out["brands"], key=lambda x: ({"dev": 0, "holdout": 1, "train": 2}[x["split"]], x["slug"])):
        for up in UPLOADS:
            u = b["uploads"][up]
            fp, lm = u["first_pass"], u["first_pass"]["lines"]
            st = fp["status"] + (f" ({', '.join(fp['failed_checks'])})" if fp["failed_checks"] else "")
            L.append(f"| {b['slug']} | {b['split']} | {up} | {st} | {fp['review_items']} | {pct(lm['coverage'])} | "
                     f"{pct(lm['precision'])} | {u['final']['status']} | {u['receipts']['pipeline_error_pct']}% | "
                     f"{u['receipts']['naive_overstatement_pct']}% |")
    if out.get("faults"):
        df = pd.DataFrame(out["faults"])
        L += ["", "## Fault injection", "",
              "Each fault is applied to upload 1 after its first review, when the clean files pass. "
              "Blocked means a tie-out failed that passes on the clean files.", "",
              "| fault | split | runs | blocked | held for review | repaired | silently accepted |",
              "|---|---|---|---|---|---|---|"]
        for (f, d), g in df.groupby(["fault", "description"], sort=False):
            for sp, h in g.groupby("split"):
                L.append(f"| {d} | {sp} | {len(h)} | {int(h['blocked'].sum())} | "
                         f"{int(h['held_for_review'].sum())} | {int(h['repaired'].sum())} | "
                         f"{int(h['silently_accepted'].sum())} |")
    (RES / "results.md").write_text("\n".join(L) + "\n")


